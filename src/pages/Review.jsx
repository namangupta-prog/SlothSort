const db = globalThis.__B44_DB__ || { auth:{ isAuthenticated: async()=>false, me: async()=>null }, entities:new Proxy({}, { get:()=>({ filter:async()=>[], get:async()=>null, create:async()=>({}), update:async()=>({}), delete:async()=>({}) }) }), integrations:{ Core:{ UploadFile:async()=>({ file_url:'' }) } } };

import { useCallback, useEffect, useState } from "react";
import { Link } from "react-router-dom";

import { Check, ListChecks } from "lucide-react";
import PageHeader from "@/components/PageHeader";
import EmptyState from "@/components/EmptyState";
import DemoBanner from "@/components/DemoBanner";
import ReviewCard from "@/components/review/ReviewCard";
import { Button } from "@/components/ui/button";
import { Skeleton } from "@/components/ui/skeleton";
import { useToast } from "@/components/ui/use-toast";
import { logActivity } from "@/lib/activity";

export default function Review() {
  const { toast } = useToast();
  const [records, setRecords] = useState([]);
  const [loading, setLoading] = useState(true);
  const [pendingId, setPendingId] = useState(null);
  const [pendingAction, setPendingAction] = useState(null);
  const [bulkBusy, setBulkBusy] = useState(false);

  const load = useCallback(async () => {
    const page = await db.entities.FileRecord.filter(
      { status: "suggested" },
      { sort: "created_date", limit: 50 }
    );
    setRecords(page.items || []);
    setLoading(false);
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  const decide = async (record, status) => {
    setPendingId(record.id);
    setPendingAction(status);
    try {
      await db.entities.FileRecord.update(record.id, {
        status,
        reviewed_date: new Date().toISOString()
      });
      await logActivity({
        action: status,
        title: `${status === "approved" ? "Approved" : "Rejected"} "${record.suggested_filename}"`,
        detail:
          status === "approved"
            ? `${record.filename} → ${record.destination_folder}`
            : `${record.filename} stays exactly where it is.`,
        file_id: record.id,
        filename: record.filename,
        previous: { status: "suggested" }
      });
      setRecords((prev) => prev.filter((item) => item.id !== record.id));
    } finally {
      setPendingId(null);
      setPendingAction(null);
    }
  };

  const approveAll = async () => {
    if (!records.length) return;
    const ids = records.map((record) => record.id);
    const count = ids.length;
    setBulkBusy(true);
    try {
      await db.entities.FileRecord.bulkUpdate(
        ids.map((id) => ({ id, status: "approved", reviewed_date: new Date().toISOString() }))
      );
      await logActivity({
        action: "approve",
        title: `Approved ${count} suggestion${count === 1 ? "" : "s"}`,
        detail: "Bulk approved from the review queue.",
        file_ids: ids,
        previous: { status: "suggested" }
      });
      setRecords([]);
      toast({ title: `${count} suggestion${count === 1 ? "" : "s"} approved` });
    } finally {
      setBulkBusy(false);
    }
  };

  const anyDemo = records.some((record) => record.ai_source === "demo");

  return (
    <div className="space-y-6">
      <PageHeader
        eyebrow="Step 2"
        title="Approve or reject each suggestion"
        description="Every file needs a decision from you. Approving only records your choice — the export is where a plan leaves the app."
      >
        {records.length ? (
          <Button className="rounded-full" onClick={approveAll} disabled={bulkBusy}>
            <Check className="mr-2 h-4 w-4" />
            {bulkBusy ? "Approving…" : `Approve all ${records.length}`}
          </Button>
        ) : null}
      </PageHeader>

      {anyDemo ? (
        <DemoBanner>
          Some of these suggestions were generated by SlothSort's built-in demo rules, not by a model.
          They're labelled <span className="font-semibold">Demo data</span> below.
        </DemoBanner>
      ) : null}

      {loading ? (
        <div className="space-y-3">
          <Skeleton className="h-44 w-full rounded-3xl" />
          <Skeleton className="h-44 w-full rounded-3xl" />
        </div>
      ) : records.length ? (
        <div className="space-y-3">
          {records.map((record) => (
            <ReviewCard
              key={record.id}
              record={record}
              pending={pendingId === record.id ? pendingAction : null}
              onApprove={(item) => decide(item, "approved")}
              onReject={(item) => decide(item, "rejected")}
            />
          ))}
        </div>
      ) : (
        <EmptyState
          icon={ListChecks}
          title="Nothing waiting for review"
          description="Add files on the upload page and ask for suggestions — they'll line up here for your decision."
        >
          <Button asChild className="rounded-full">
            <Link to="/upload">Add files</Link>
          </Button>
        </EmptyState>
      )}
    </div>
  );
}